package com.termux.app.models.wireguard;

import android.content.Context;
import android.content.SharedPreferences;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.io.StringReader;
import java.util.ArrayList;
import java.util.List;

public class WireGuardNetworkStore {
    private static final String PREF_NAME = "server_hub_wireguard_prefs";
    private static final String KEY_CONFIG = "wireguard_config";
    private static final String KEY_PORTS = "port_rules";
    private static final String KEY_TUNNEL_ACTIVE = "tunnel_active";

    private final SharedPreferences prefs;
    private final Context context;

    public WireGuardNetworkStore(@NonNull Context context) {
        this.context = context.getApplicationContext();
        this.prefs = this.context.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE);
    }

    @Nullable
    public WireGuardConfig getConfig() {
        String json = prefs.getString(KEY_CONFIG, null);
        return WireGuardConfig.fromJson(json);
    }

    public void saveConfig(@Nullable WireGuardConfig config) {
        if (config == null) {
            prefs.edit().remove(KEY_CONFIG).apply();
            return;
        }
        try {
            prefs.edit().putString(KEY_CONFIG, config.toJson().toString()).apply();
        } catch (JSONException ignored) {}
    }

    @NonNull
    public List<PortRule> getPortRules() {
        List<PortRule> list = new ArrayList<>();
        String json = prefs.getString(KEY_PORTS, null);
        if (json == null || json.trim().isEmpty()) {
            // Default rules: SSH external 2222 -> internal 8022 (TCP), NVGT Game 7777 -> 7777 (UDP)
            list.add(new PortRule("SSH Access", "tcp", 2222, "127.0.0.1", 8022, true));
            list.add(new PortRule("NVGT Game Server", "udp", 7777, "127.0.0.1", 7777, true));
            savePortRules(list);
            return list;
        }

        try {
            JSONArray arr = new JSONArray(json);
            for (int i = 0; i < arr.length(); i++) {
                JSONObject obj = arr.getJSONObject(i);
                PortRule rule = PortRule.fromJson(obj);
                if (rule != null) list.add(rule);
            }
        } catch (JSONException ignored) {}

        return list;
    }

    public void savePortRules(@NonNull List<PortRule> rules) {
        JSONArray arr = new JSONArray();
        for (PortRule rule : rules) {
            try {
                arr.put(rule.toJson());
            } catch (JSONException ignored) {}
        }
        prefs.edit().putString(KEY_PORTS, arr.toString()).apply();
    }

    public void addPortRule(@NonNull PortRule rule) {
        List<PortRule> current = getPortRules();
        current.add(rule);
        savePortRules(current);
    }

    public void removePortRule(@NonNull String id) {
        List<PortRule> current = getPortRules();
        for (int i = 0; i < current.size(); i++) {
            if (current.get(i).getId().equals(id)) {
                current.remove(i);
                break;
            }
        }
        savePortRules(current);
    }

    public boolean isTunnelActive() {
        return prefs.getBoolean(KEY_TUNNEL_ACTIVE, false);
    }

    public void setTunnelActive(boolean active) {
        prefs.edit().putBoolean(KEY_TUNNEL_ACTIVE, active).apply();
    }

    @NonNull
    public File getWireproxyConfigFile() {
        File configDir = new File(context.getFilesDir(), "wireguard");
        if (!configDir.exists()) configDir.mkdirs();
        return new File(configDir, "wireproxy.conf");
    }

    public boolean generateWireproxyConfig() {
        WireGuardConfig config = getConfig();
        if (config == null || !config.isValid()) return false;

        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by Game Server Hub\n\n");

        String raw = config.getRawConfig();
        if (raw != null && !raw.trim().isEmpty()) {
            // Use the original config sections from the .conf file to preserve KeepAlive, MTU, etc.
            try (BufferedReader r = new BufferedReader(new StringReader(raw))) {
                String line;
                boolean inTunnelSection = false;
                while ((line = r.readLine()) != null) {
                    String trimmed = line.trim();
                    if (trimmed.startsWith("[") && trimmed.endsWith("]")) {
                        String s = trimmed.substring(1, trimmed.length() - 1).trim();
                        if (s.equalsIgnoreCase("TCPServerTunnel") || s.equalsIgnoreCase("UDPServerTunnel") || s.equalsIgnoreCase("Server")) {
                            inTunnelSection = true;
                            continue;
                        } else {
                            inTunnelSection = false;
                        }
                    }
                    if (!inTunnelSection) {
                        sb.append(line).append("\n");
                    }
                }
            } catch (IOException ignored) {}
        } else {
            sb.append("[Interface]\n");
            sb.append("PrivateKey = ").append(config.getPrivateKey()).append("\n");
            sb.append("Address = ").append(config.getAddress()).append("\n");
            if (!config.getDns().isEmpty()) {
                sb.append("DNS = ").append(config.getDns()).append("\n");
            }
            sb.append("\n[Peer]\n");
            sb.append("PublicKey = ").append(config.getPeerPublicKey()).append("\n");
            sb.append("Endpoint = ").append(config.getPeerEndpoint()).append("\n");
            sb.append("AllowedIPs = ").append(config.getAllowedIps().isEmpty() ? "::/0, 0.0.0.0/0" : config.getAllowedIps()).append("\n");
            sb.append("PersistentKeepalive = 25\n");
        }

        // Append port forwarding rules with the exact syntax expected by wireproxy
        List<PortRule> rules = getPortRules();
        for (PortRule rule : rules) {
            if (!rule.isEnabled()) continue;
            if ("udp".equalsIgnoreCase(rule.getProtocol())) {
                sb.append("\n[UDPServerTunnel]\n");
                sb.append("ListenPort = ").append(rule.getListenPort()).append("\n");
                sb.append("Target = ").append(rule.getTargetHost()).append(":").append(rule.getDestinationPort()).append("\n");
            } else {
                sb.append("\n[TCPServerTunnel]\n");
                sb.append("ListenPort = ").append(rule.getListenPort()).append("\n");
                sb.append("Target = ").append(rule.getTargetHost()).append(":").append(rule.getDestinationPort()).append("\n");
            }
        }

        File outFile = getWireproxyConfigFile();
        try (FileWriter writer = new FileWriter(outFile)) {
            writer.write(sb.toString());
            return true;
        } catch (IOException e) {
            return false;
        }
    }
}
